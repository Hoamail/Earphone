#!/usr/bin/env python3
"""
beep_off.py - find and disable the connect / case / charging chime.

The chime is generated by the accessory firmware. AAP exposes two controls that
can mute it:

    0x1F  ChimeVolume     volume of the accessory-generated tones
    0x31  InCaseTone      tone played by the case / on power-up

Which one actually silences your unit is not knowable from the protocol dump -
clone firmwares reuse ids inconsistently - so this walks the candidates and asks
you to listen after each one. Closing the case drops the AAP socket, so every
round reconnects.

    sudo python3 beep_off.py --mac 41:42:23:76:ED:B8
    sudo python3 beep_off.py --mac ... --list
    sudo python3 beep_off.py --mac ... --read
    sudo python3 beep_off.py --mac ... --apply 0x1F=0        # known winner
    sudo python3 beep_off.py --mac ... --apply 0x1F=0,0x31=0
"""

import argparse
import json
import sys
import time

import aap_l2cap as A

# ordered: least destructive first. A value of 0 means "silent".
CANDIDATES = [
    ("ChimeVolume = 0", [(0x1F, 0)]),
    ("InCaseTone = 0", [(0x31, 0)]),
    ("ChimeVolume = 0 and InCaseTone = 0", [(0x1F, 0), (0x31, 0)]),
]

PROFILE = "beep-off.json"


# ------------------------------------------------------------------ transport
def session(mac, tries=10, delay=2.5):
    last = None
    for i in range(1, tries + 1):
        try:
            s, label = A.connect(mac)
            replies = A.xfer(s, A.HANDSHAKE, 1.0, quiet=True)
            if not any(p[:4] == bytes([0x01, 0x00, 0x04, 0x00]) for p in replies):
                s.close()
                last = "no ACK"
                raise OSError("no ACK")
            A.xfer(s, A.SET_FEATURES, 0.3, quiet=True)
            return s
        except OSError as e:
            last = e
            print(f"  waiting for the accessory ({i}/{tries}): {e}")
            time.sleep(delay)
    sys.exit(f"could not reach the accessory: {last}")


def write_one(s, cid, value):
    """Write a control, return (accepted, echoed_value)."""
    echoes = A.xfer(s, A.ctrl(cid, value, 0, 0, 0), 0.9, quiet=True)
    for pkt in echoes:
        if len(pkt) >= 11 and pkt[:6] == A.HEADER + bytes([0x09, 0x00]) and pkt[6] == cid:
            return True, bytes(pkt[7:11])
    return False, None


def snapshot(s, seconds=2.5):
    state, _ = A.read_controls(s, seconds)
    return {f"0x{c:02X}": v.hex(" ") for c, v in state.items()}


# ------------------------------------------------------------------- commands
def cmd_read(mac):
    s = session(mac)
    try:
        state, _ = A.read_controls(s, 3.5)
    finally:
        s.close()
    if not state:
        print("no controls pushed; reconnect the buds and retry")
        return
    print("\ncontrols the accessory reports:")
    for cid in sorted(state):
        mark = "  <-- chime candidate" if cid in (0x1F, 0x31) else ""
        print("  " + A.pretty(cid, state[cid]) + mark)
    if 0x1F not in state and 0x31 not in state:
        print("\nneither 0x1F nor 0x31 was reported. They may still accept writes -"
              "\nrun without --read to try.")


def cmd_apply(mac, spec, out=PROFILE):
    pairs = []
    for item in spec.split(","):
        key, _, val = item.partition("=")
        pairs.append((int(key, 0), int(val or "0", 0)))
    s = session(mac)
    try:
        before = snapshot(s)
        for cid, value in pairs:
            ok, echo = write_one(s, cid, value)
            name = A.CTRL_NAMES.get(cid, hex(cid))
            if ok:
                print(f"  {name}(0x{cid:02X}) = {value}   echoed {echo.hex(' ')}")
            else:
                print(f"  {name}(0x{cid:02X}) = {value}   no echo - firmware ignored it")
        after = snapshot(s)
    finally:
        s.close()
    save_profile(out, before, after, pairs)
    print(f"\nprofile -> {out}")
    print("now close the case, wait 3 s, open it: is the beep gone?")


def save_profile(path, before, after, pairs):
    doc = {
        "applied_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "writes": {f"0x{c:02X}": v for c, v in pairs},
        "before": before,
        "after": after,
    }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1)


def cmd_hunt(mac):
    print(__doc__.split("\n\n")[0])
    print("\nFor each candidate you close the case, wait, open it, and answer whether")
    print("it still beeped. Keep the buds out of the case while answering.\n")

    for idx, (label, writes) in enumerate(CANDIDATES, 1):
        print(f"\n=== candidate {idx}/{len(CANDIDATES)}: {label} ===")
        if input("  try this one? [Y/n/skip] ").strip().lower() in ("n", "skip", "s"):
            continue

        s = session(mac)
        try:
            before = snapshot(s)
        except OSError as e:
            print(f"  read failed: {e}")
            s.close()
            continue

        accepted = []
        for cid, value in writes:
            ok, echo = write_one(s, cid, value)
            name = A.CTRL_NAMES.get(cid, hex(cid))
            print(f"  write {name}(0x{cid:02X}) = {value} -> "
                  + (f"echo {echo.hex(' ')}" if ok else "no echo (unsupported)"))
            if ok:
                accepted.append((cid, value))
        time.sleep(1.0)
        s.close()

        if not accepted:
            print("  this firmware does not expose that control; skipping the test.")
            continue

        print("\n  Now: close the case, wait 3 s, open it.")
        while True:
            ans = input("  still beeping? [y/n] ").strip().lower()
            if ans in ("y", "n"):
                break
        if ans == "y":
            print("  not it. reverting this candidate.")
            s = session(mac)
            try:
                for cid, _v in accepted:
                    old = before.get(f"0x{cid:02X}", "00 00 00 00")
                    write_one(s, cid, int(old[0:2], 16))
            finally:
                s.close()
            continue

        save_profile(PROFILE, before, {}, accepted)
        print(f"\n  WINNER: {label}")
        print(f"  saved -> {PROFILE}")
        print("  re-apply any time with:")
        print("    sudo python3 beep_off.py --mac " + mac
              + " --apply " + ",".join(f"0x{c:02X}={v}" for c, v in accepted))
        return

    print("\nNo candidate silenced it. That means the tone is emitted before the")
    print("host link exists (power-on / charging chime straight from the firmware).")
    print("Nothing over AAP can mute that one; it is baked into the image.")


def cmd_restore(mac, path):
    with open(path, encoding="utf-8") as f:
        doc = json.load(f)
    values = doc.get("writes", {})
    if not values:
        sys.exit(f"{path} has no 'writes' map")
    s = session(mac)
    try:
        for key, value in sorted(values.items()):
            cid = int(key, 0)
            ok, echo = write_one(s, cid, 0)
            name = A.CTRL_NAMES.get(cid, hex(cid))
            print(f"  restored {name}(0x{cid:02X}) -> {echo.hex(' ') if ok else 'no echo'}")
    finally:
        s.close()


def cmd_experiment(mac, cid, value=0):
    """Snapshot one control, write a test value, and tell the user how to undo."""
    s = session(mac)
    try:
        before = snapshot(s)
        ok, _echo = write_one(s, cid, value)
    finally:
        s.close()
    name = A.CTRL_NAMES.get(cid, hex(cid))
    old = before.get(f"0x{cid:02X}", "00 00 00 00")
    path = f"experiment-0x{cid:02X}.json"
    save_profile(path, before, {}, [(cid, value)])
    print(f"\nwrote {name}(0x{cid:02X}) = {value}  "
          + ("(accepted)" if ok else "(no echo - firmware ignored it)"))
    print(f"was: {old}")
    print(f"undo: sudo python3 beep_off.py --mac {mac} --apply 0x{cid:02X}={int(old[0:2], 16)}")


def main():
    ap = argparse.ArgumentParser(description="disable the accessory chime over AAP")
    ap.add_argument("--mac", required=True)
    ap.add_argument("--read", action="store_true", help="only print current chime controls")
    ap.add_argument("--apply", metavar="0x1F=0[,0x31=0]", help="write known values")
    ap.add_argument("--restore", metavar="FILE", help="write back values from a profile")
    ap.add_argument("--experiment", metavar="CID", help="snapshot one control, write 0 to it")
    ap.add_argument("--list", action="store_true", help="show the candidate list")
    args = ap.parse_args()

    if args.list:
        for i, (label, writes) in enumerate(CANDIDATES, 1):
            spec = ", ".join(f"0x{c:02X}={v}" for c, v in writes)
            print(f"{i}. {label:<40} [{spec}]")
        return
    if args.read:
        return cmd_read(args.mac)
    if args.apply:
        return cmd_apply(args.mac, args.apply)
    if args.restore:
        return cmd_restore(args.mac, args.restore)
    if args.experiment:
        return cmd_experiment(args.mac, int(args.experiment, 0))
    return cmd_hunt(args.mac)


if __name__ == "__main__":
    main()
